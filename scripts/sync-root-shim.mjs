#!/usr/bin/env node
/**
 * sync-root-shim.mjs — regenerate the repository-root plugin shim from
 * `packages/helmd` (the actual plugin package, `@adwmc/helm-d`).
 *
 * WHY: DSH resolves a plugin row's module specifier by the package name it
 * actually mounted. A git install of the *bare repository URL* mounts the root
 * package (`helmd`), not `@adwmc/helm-d`, so the root needs its own
 * `cordis.patch.yml` / `preset.generated.patch.yml` / `client.js` whose row
 * names and client module id read `helmd`. Everything else is byte-identical
 * to the subpackage's file — this script is the single writer of that delta.
 *
 * Usage:
 *   node scripts/sync-root-shim.mjs           # rewrite the three root files
 *   node scripts/sync-root-shim.mjs --check   # exit 1 if they drifted
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkgDir = join(repoRoot, 'packages', 'helmd')
const ROOT_NAME = 'helmd'
const PKG_NAME = '@adwmc/helm-d'
const CHECK = process.argv.includes('--check')

/** Target path -> [source path, transform, header?]. Each transform rewrites ONLY
 *  the package-name occurrences that must name the mounted root package. A
 *  `header` is prepended (only when the file does not already carry it). */
const FILES = [
  {
    target: 'cordis.patch.yml',
    source: join(pkgDir, 'cordis.patch.yml'),
    header: `# Generated by scripts/sync-root-shim.mjs from packages/helmd/cordis.patch.yml — do not edit.
# Lets the bare repository URL install as a DSH plugin: the Loader names a row
# after the package it mounted, and a root install mounts \`helmd\`, not
# \`@adwmc/helm-d\`. Only that name differs from the subpackage's file.
`,
    transform: (text) => text.split(`name: '${PKG_NAME}'`).join(`name: '${ROOT_NAME}'`),
  },
  {
    target: 'preset.generated.patch.yml',
    source: join(pkgDir, 'preset.generated.patch.yml'),
    transform: (text) => text.split(`name: '${PKG_NAME}/agent'`).join(`name: '${ROOT_NAME}/agent'`),
  },
  {
    target: 'client.js',
    source: join(pkgDir, 'client.js'),
    transform: (text) => {
      const head = `window.__ModuleLoader__.load({ id: "${PKG_NAME}", factory: (require) => {`
      if (!text.startsWith(head)) {
        throw new Error(`client.js: expected the bundle to open with ${JSON.stringify(head)}; update sync-root-shim.mjs`)
      }
      let out = `window.__ModuleLoader__.load({ id: "${ROOT_NAME}", factory: (require) => {` + text.slice(head.length)
      // The alias block must alias onto the id this bundle actually registers.
      const aliasFrom = `window.__ModuleLoader__.require("${PKG_NAME}")`
      if (!out.includes(aliasFrom)) {
        throw new Error(`client.js: alias block no longer requires ${PKG_NAME}; update sync-root-shim.mjs`)
      }
      out = out.split(aliasFrom).join(`window.__ModuleLoader__.require("${ROOT_NAME}")`)
      return out
    },
  },
]

let drifted = false
for (const { target, source, transform, header } of FILES) {
  if (!existsSync(source)) throw new Error(`missing source ${source}`)
  const expected = (header ?? '') + transform(readFileSync(source, 'utf8'))
  const targetPath = join(repoRoot, target)
  const current = existsSync(targetPath) ? readFileSync(targetPath, 'utf8') : undefined
  if (current === expected) {
    if (!CHECK) console.log(`unchanged  ${target}`)
    continue
  }
  drifted = true
  if (CHECK) {
    console.error(`drifted    ${target} — run: node scripts/sync-root-shim.mjs`)
    continue
  }
  writeFileSync(targetPath, expected, 'utf8')
  console.log(`rewritten  ${target}`)
}
if (CHECK && drifted) process.exit(1)
